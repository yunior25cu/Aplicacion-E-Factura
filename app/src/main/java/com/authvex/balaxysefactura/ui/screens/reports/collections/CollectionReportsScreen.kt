@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun CollectionReportsScreen(
    onNavigateBack: () -> Unit,
    onNavigateToReceivables: () -> Unit,
    onNavigateToAging: () -> Unit,
    onNavigateToCollected: () -> Unit
) {
    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("Informes de Cobros") },
                navigationIcon = {
                    IconButton(onClick = onNavigateBack) {
                        Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Regresar")
                    }
                },
                colors = TopAppBarDefaults.topAppBarColors(containerColor = MaterialTheme.colorScheme.surface)
            )
        }
    ) { innerPadding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(innerPadding)
                .background(MaterialTheme.colorScheme.background)
                .verticalScroll(rememberScrollState())
                .padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(16.dp)
        ) {
            ReportCategoryCard(
                title = "Estado de Cuentas por Cobrar",
                subtitle = "Saldo pendiente, cobrado y ajustes por cliente",
                icon = Icons.Default.AccountBalance,
                color = MaterialTheme.colorScheme.primary,
                onClick = onNavigateToReceivables
            )

            ReportCategoryCard(
                title = "Antigüedad de Deuda (Aging)",
                subtitle = "Deuda no vencida y vencida en tramos de 30 días",
                icon = Icons.Default.CalendarMonth,
                color = Color(0xFFF57C00),
                onClick = onNavigateToAging
            )

            ReportCategoryCard(
                title = "Cobros Realizados",
                subtitle = "Historial y resumen de cobros confirmados",
                icon = Icons.Default.Payments,
                color = Color(0xFF43A047),
                onClick = onNavigateToCollected
            )
        }
    }
}

@Composable
fun ReportCategoryCard(
    title: String,
    subtitle: String,
    icon: ImageVector,
    color: Color,
    onClick: () -> Unit
) {
    Card(
        modifier = Modifier
            .fillMaxWidth()
            .clickable { onClick() },
        shape = RoundedCornerShape(16.dp),
        colors = CardDefaults.cardColors(containerColor = Color.White),
        elevation = CardDefaults.cardElevation(defaultElevation = 2.dp)
    ) {
        Row(
            modifier = Modifier.padding(16.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            Surface(
                modifier = Modifier.size(48.dp),
                shape = RoundedCornerShape(12.dp),
                color = color.copy(alpha = 0.12f)
            ) {
                Box(contentAlignment = Alignment.Center) {
                    Icon(
                        imageVector = icon,
                        contentDescription = null,
                        tint = color,
                        modifier = Modifier.size(24.dp)
                    )
                }
            }

            Spacer(modifier = Modifier.width(16.dp))

            Column(modifier = Modifier.weight(1f)) {
                Text(
                    text = title,
                    style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.Bold,
                    color = MaterialTheme.colorScheme.onSurface
                )
                Spacer(modifier = Modifier.height(2.dp))
                Text(
                    text = subtitle,
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurface.copy(alpha = 0.6f)
                )
            }
        }
    }
}
